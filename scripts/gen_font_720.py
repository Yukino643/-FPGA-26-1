"""生成720p界面实际使用的原生32像素字模；--check只比较，不改构建输入。"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
WINDOWS = ('炬屏—双模HDMI多媒体系统', '广告模式', '应急模式', '运行 00:00:00')
PRESETS = ('欢迎使用炬屏—双模HDMI多媒体系统', '双屏协作 一屏操作 一屏呈现', '图片 字幕 音乐 波形 随心设置')
BADGE = '视界'
# 字模地址固定；正文删除标点不重排已验证的标题/时间/标签字模。
# 三个未使用标点槽保留，ROM字节和物理bank大小不变，字幕表不再引用。
CHARS = ' 炬屏—双模HDMI多媒体系统广告式应急运行0:123456789欢迎使用！协作，一操呈现图片、字幕音乐波形随心设置视界'

def generate():
    if len(CHARS) > 64:
        raise ValueError('实际用字超过现有64格字库容量，必须先评估资源')
    required = set(''.join(WINDOWS) + '123456789' + ''.join(PRESETS) + BADGE)
    missing = required - set(CHARS)
    if missing or len(set(CHARS)) != len(CHARS):
        raise ValueError(f'固定字模地址表缺字或存在重复: {sorted(missing)}')
    font_path = Path('C:/Windows/Fonts/simhei.ttf')
    if not font_path.is_file():
        raise RuntimeError('缺少原生中文字体 C:/Windows/Fonts/simhei.ttf')
    font = ImageFont.truetype(str(font_path), 30)
    rows = []
    for ch in CHARS:
        img = Image.new('L', (32,32), 0)
        draw = ImageDraw.Draw(img)
        bx,by,ex,ey = draw.textbbox((0,0),ch,font=font)
        draw.text(((32-ex+bx)//2-bx,(32-ey+by)//2-by),ch,font=font,fill=255)
        # 仅改善全角HDMI格内的拉丁墨迹宽度；字格、字号和ROM深度不变。
        if ch in 'HDMI':
            bbox = img.getbbox()
            if bbox is None:
                raise RuntimeError(f'拉丁字形为空: {ch}')
            ink = img.crop(bbox)
            if ch == 'I':
                # 黑体I只有窄竖笔，直接拉宽会变实心块；使用明确的横杠/竖笔结构。
                ink = Image.new('L', (24, ink.height), 0)
                strokes = ImageDraw.Draw(ink)
                strokes.rectangle((0, 0, 23, 2), fill=255)
                strokes.rectangle((10, 0, 13, ink.height-1), fill=255)
                strokes.rectangle((0, ink.height-3, 23, ink.height-1), fill=255)
            else:
                ink = ink.resize((24, ink.height), Image.Resampling.NEAREST)
            img = Image.new('L', (32,32), 0)
            img.paste(ink, (4, (32-ink.height)//2))
        rows += [sum((img.getpixel((x,y))>=100) << (31-x) for x in range(32)) for y in range(32)]
    depth = 1 << (len(rows)-1).bit_length()
    aw = (depth-1).bit_length()
    rows += [0]*(depth-len(rows))
    rom = f'''// Generated by gen_font_720.py; native 32px, {len(CHARS)} glyphs.
module font_rom_720(input wire clk, input wire [5:0] glyph,
                    input wire [4:0] row, output reg [31:0] bits);
    reg [31:0] mem [0:{depth-1}];
    wire [{aw-1}:0] address = {{glyph, row}};
    initial $readmemh("D:/FPGA/code/example/rtl/video/font_720.hex",mem);
    always @(posedge clk) bits <= mem[address];
endmodule
'''
    text = ['// Generated by gen_font_720.py; 0 = blank.',
            'module osd_text_720(input wire [1:0] win,input wire [5:0] col,output reg [5:0] glyph);',
            'always @(*) begin', 'case ({win,col})']
    for wi, window in enumerate(WINDOWS):
        for ci, ch in enumerate(window):
            label = 'blank' if ch == ' ' else ch
            text += [f"    {{2'd{wi},6'd{ci}}}: glyph=6'd{CHARS.index(ch)}; // {label}"]
    text += ['default: glyph=0;', 'endcase', 'end', 'endmodule']
    lookup = ['// Generated digit and colon glyph indexes.']
    for ch in '0123456789:':
        name = 'COLON' if ch==':' else 'DIGIT_'+ch
        lookup += [f"localparam [5:0] {name}=6'd{CHARS.index(ch)};"]
    for name,ch in (('BADGE_SHI','视'),('BADGE_JIE','界')):
        lookup += [f"localparam [5:0] {name}=6'd{CHARS.index(ch)};"]
    subtitle = ['// Generated preset cells; 64 cells per cycle, blank-padded.',
                'module subtitle_text_720(input wire [1:0] preset, input wire [5:0] col, output reg [5:0] glyph);',
                'always @* begin', 'case ({preset,col})']
    for pi,line in enumerate(PRESETS):
        if len(line)>64:raise ValueError('字幕超出64字格')
        for ci,ch in enumerate(line.ljust(64)):
            subtitle += [f"    {{2'd{pi},6'd{ci}}}: glyph=6'd{CHARS.index(ch)}; // {ch}"]
    subtitle += ['default: glyph=0;','endcase','end','endmodule']
    return {
        'rtl/video/font_720.hex': ''.join(f'{row:08X}\n' for row in rows),
        'rtl/video/font_rom_720.v': rom,
        'rtl/video/osd_text_720.v': '\n'.join(text)+'\n',
        'rtl/video/font_720_map.vh': '\n'.join(lookup)+'\n',
        'rtl/video/subtitle_text_720.v': '\n'.join(subtitle)+'\n',
    }

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for name, content in generate().items():
        path=ROOT/name
        if args.check:
            if not path.is_file() or path.read_bytes()!=content.encode('utf-8'):
                raise RuntimeError(f'生成物不同步: {name}')
        else:
            path.write_text(content,encoding='utf-8',newline='\n')
    print('FONT720 PASS native 32px, deterministic generated files')
