#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_font.py — 光栅化 ASCII 8x16 字库，生成:
  1. rtl/ctrl/font_rom_ascii.v   综合用 ROM（case 128bit 字模）
  2. sim/font_ascii.hex          仿真用 $readmemh 数据
用 Windows 自带 Consolas 渲染，阈值 1bpp。
字形存储约定: glyph[127:120]=第0行(顶行)，每行 8bit，MSB=最左像素。
"""
import os
from PIL import Image, ImageDraw, ImageFont

OUT_V   = os.path.join(os.path.dirname(__file__), "..", "rtl", "ctrl", "font_rom_ascii.v")
OUT_HEX = os.path.join(os.path.dirname(__file__), "..", "sim", "font_ascii.hex")
CW, CH = 8, 16
FIRST, LAST = 0x20, 0x7E

def rasterize():
    font = ImageFont.truetype("consola.ttf", 14)
    glyphs = {}
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img = Image.new("L", (CW, CH), 0)
        d = ImageDraw.Draw(img)
        # 用 font.getbbox 定位，水平/垂直居中
        bbox = d.textbbox((0, 0), ch, font=font)
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        x = (CW - w) // 2 - bbox[0]
        y = (CH - h) // 2 - bbox[1]
        d.text((x, y), ch, fill=255, font=font)
        px = img.load()
        rows = []
        for r in range(CH):
            bits = 0
            for c in range(CW):
                if px[c, r] > 100:
                    bits |= 1 << (7 - c)   # MSB = 最左
            rows.append(bits)
        glyphs[code] = rows
    return glyphs

def emit_verilog(glyphs):
    # A2: BRAM 同步读版（2048x8，addr={char[6:0],row}；绝对路径正斜杠）
    lines = []
    lines.append("// Auto-generated by scripts/gen_font.py - DO NOT EDIT")
    lines.append("// ASCII 0x20-0x7E, 8x16 1bpp. glyph[127:120]=row0(top), MSB=leftmost pixel.")
    lines.append("// A2: BRAM 同步读（消费方须将坐标打 1 拍与 O_bits 对齐）")
    lines.append("// 数据: rtl/ctrl/font_ascii_bram.hex（同脚本 emit_bram_hex 生成）")
    lines.append("module font_rom_ascii(")
    lines.append("    input  wire        I_clk,")
    lines.append("    input  wire [7:0]  I_char,   // ASCII code")
    lines.append("    input  wire [3:0]  I_row,    // 0=top .. 15=bottom")
    lines.append("    output reg  [7:0]  O_bits    // 8 pixels, O_bits[7]=leftmost")
    lines.append(");")
    lines.append("    reg [7:0] mem [0:2047];")
    lines.append('    initial $readmemh("D:/FPGA/code/example/rtl/ctrl/font_ascii_bram.hex", mem);')
    lines.append("")
    lines.append("    always @(posedge I_clk)")
    lines.append("        O_bits <= mem[{I_char[6:0], I_row}];")
    lines.append("")
    lines.append("endmodule")
    with open(OUT_V, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

def emit_bram_hex(glyphs):
    """A2: ASCII BRAM 初始化 hex（$readmemh 用）：地址 = char*16+row，数据 = 8bit。
    与 font_rom_ascii.v 的 mem[{I_char[6:0], I_row}] 寻址严格对应。深度 2048。"""
    depth = 2048
    out = os.path.join(os.path.dirname(__file__), "..", "rtl", "ctrl", "font_ascii_bram.hex")
    rows = []
    for code in range(0, FIRST):        # 0x00-0x1F blank
        rows += ["00"] * 16
    for code in range(FIRST, LAST + 1):
        for bits in glyphs[code]:
            rows.append("%02X" % bits)
    for code in range(LAST + 1, 128):
        rows += ["00"] * 16
    rows += ["00"] * (depth - len(rows))
    nl = chr(10)
    with open(out, "w", newline="") as f:
        f.write(nl.join(rows) + nl)

def emit_hex(glyphs):
    with open(OUT_HEX, "w", newline="\n") as f:
        # 每行一个字符的 32 位 hex（128bit 按 4×32bit 展开，地址 = char*16+row 太长；
        # 仿真用紧凑格式: 每字符一行 128bit hex）
        for code in range(FIRST, LAST + 1):
            val = 0
            for r, bits in enumerate(glyphs[code]):
                val |= bits << (120 - 8 * r)
            f.write(f"{val:032X}\n")

if __name__ == "__main__":
    g = rasterize()
    emit_verilog(g)
    emit_hex(g)
    emit_bram_hex(g)
    n = sum(1 for code in g for b in g[code] if b)
    print(f"OK: {len(g)} glyphs, {n} set pixels -> {os.path.normpath(OUT_V)}")
