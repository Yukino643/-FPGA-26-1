#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_font_cjk.py — 中文字库光栅化（16x16 1bpp）
输入: scripts/osd_strings.txt（每行一条 OSD/字幕/告警字符串，全部唯一字符入库）
输出:
  1. rtl/video/font_rom_cjk.v    字模 ROM（按字形序号索引, 16bit/行, MSB=最左）
  2. rtl/video/osd_text_rom.v    固定文本窗内容 ROM（窗口×列 → 字形序号）
                                 单元编码: 0x0000..N-1 = CJK 字形序号
                                           0x0100+code  = ASCII(半宽, 居中画在16px格内)
  3. sim/font_cjk.hex            仿真用每字形 256bit hex
约定: 字形序号 0 保留为"空白格"(全 0)。
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE    = os.path.dirname(os.path.abspath(__file__))
STR_TXT = os.path.join(HERE, "osd_strings.txt")
OUT_ROM = os.path.join(HERE, "..", "rtl", "video", "font_rom_cjk.v")
OUT_TXT = os.path.join(HERE, "..", "rtl", "video", "osd_text_rom.v")
OUT_HEX = os.path.join(HERE, "..", "sim", "font_cjk.hex")

CW, CH = 16, 16
FONT   = "simhei.ttf"          # C:\Windows\Fonts\simhei.ttf

# 固定文本窗定义: (窗口名, 字符串)
WINDOWS = [
    ("TITLE", "安路EG4S20多媒体播放系统"),
    ("MODE_AD", "广告模式"),
    ("MODE_EMG", "应急模式"),
    ("CLOCK", "运行 00:00:00"),   # 列3..10 由 osd_engine 用实时 BCD 时钟动态覆盖
]

def load_strings():
    with open(STR_TXT, encoding="utf-8") as f:
        lines = [l.strip() for l in f if l.strip()]
    return lines

def build_charset(lines):
    chars = []
    seen = set()
    for l in lines:
        for ch in l:
            if ch not in seen:
                seen.add(ch)
                chars.append(ch)
    return chars  # index 0 是 ' '? 不: 序号0保留空白, 字符从1开始

def rasterize(chars):
    font = ImageFont.truetype(FONT, 15)
    glyphs = {}     # char -> 16 行 16bit
    for ch in chars:
        img = Image.new("L", (CW, CH), 0)
        d = ImageDraw.Draw(img)
        bbox = d.textbbox((0, 0), ch, font=font)
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        x = (CW - w) // 2 - bbox[0]
        y = (CH - h) // 2 - bbox[1]
        d.text((x, y), ch, fill=255, font=font)
        px = img.load()
        rows = []
        for r in range(CH):
            bits = 0
            for c in range(CW):
                if px[c, r] > 100:
                    bits |= 1 << (15 - c)
            rows.append(bits)
        glyphs[ch] = rows
    return glyphs

def emit_rom(char_index, glyphs):
    # char_index: char -> 序号(1..N)；0=空白
    lines = []
    lines.append("// Auto-generated by scripts/gen_font_cjk.py — DO NOT EDIT")
    lines.append(f"// {len(char_index)} CJK glyphs 16x16 1bpp, MSB=leftmost. index 0 = blank")
    lines.append("module font_rom_cjk(")
    lines.append("    input  wire [7:0]  I_index,   // 字形序号 0=空白")
    lines.append("    input  wire [3:0]  I_row,")
    lines.append("    output reg  [15:0] O_bits")
    lines.append(");")
    lines.append("    always @(*) begin")
    lines.append("        case (I_index)")
    lines.append("            8'd0: O_bits = 16'h0000;")
    for ch, idx in sorted(char_index.items(), key=lambda kv: kv[1]):
        g = glyphs[ch]
        lines.append("            8'd%d: O_bits = ROW_%d;" % (idx, idx))
    lines.append("            default: O_bits = 16'h0000;")
    lines.append("        endcase")
    lines.append("    end")
    # 每个字形的行数据用独立 wire, 避免 256bit 大 case 一条超长
    for ch, idx in sorted(char_index.items(), key=lambda kv: kv[1]):
        g = glyphs[ch]
        vec = "".join("%04X" % b for b in g)   # row0 在最高 16bit? 约定: [255:240]=row0
        lines.append("wire [255:0] ROW_%d = 256'h%s; // '%s'" % (idx, vec, ch))
    lines.append("")
    lines.append("    // 行选通: I_row=0(顶行) → [255:240]")
    lines.append("    // 由 case 返回整行时改为:")
    lines.append("endmodule")
    # A2: BRAM 同步读版（单时钟 $readmemh 初始化，1 周期延迟；
    # iverilog/TD 通用：绝对路径正斜杠，两工具从任意 cwd 都能找到）
    lines2 = []
    lines2.append("// Auto-generated by scripts/gen_font_cjk.py - DO NOT EDIT")
    lines2.append("// %d CJK glyphs 16x16 1bpp, MSB=leftmost. index 0 = blank" % len(char_index))
    lines2.append("// A2: BRAM 同步读（消费方须将坐标打 1 拍与 O_bits 对齐）")
    lines2.append("// 数据: rtl/video/font_cjk_bram.hex（同脚本 emit_bram_hex 生成）")
    lines2.append("module font_rom_cjk(")
    lines2.append("    input  wire        I_clk,")
    lines2.append("    input  wire [7:0]  I_index,")
    lines2.append("    input  wire [3:0]  I_row,")
    lines2.append("    output reg  [15:0] O_bits")
    lines2.append(");")
    lines2.append("    reg [15:0] mem [0:4095];")
    lines2.append('    initial $readmemh("D:/FPGA/code/example/rtl/video/font_cjk_bram.hex", mem);')
    lines2.append("")
    lines2.append("    always @(posedge I_clk)")
    lines2.append("        O_bits <= mem[{I_index, I_row}];")
    lines2.append("endmodule")
    with open(OUT_ROM, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines2) + "\n")

def emit_text_rom(char_index):
    def enc_cell(ch):
        if ord(ch) < 0x80:
            return 0x0100 | ord(ch)
        return char_index[ch]
    lines = []
    lines.append("// Auto-generated by scripts/gen_font_cjk.py — DO NOT EDIT")
    lines.append("// 固定 OSD 文本窗内容; 单元: <0x100=CJK字形序号, >=0x100=ASCII(0x0100+code)")
    lines.append("module osd_text_rom(")
    lines.append("    input  wire [3:0]  I_win,")
    lines.append("    input  wire [5:0]  I_col,")
    lines.append("    output reg  [15:0] O_cell   // 0xFFFF=空格")
    lines.append(");")
    lines.append("    always @(*) begin")
    lines.append("        case ({I_win, I_col})")
    for wi, (name, text) in enumerate(WINDOWS):
        for ci, ch in enumerate(text):
            lines.append("            {4'd%d,6'd%d}: O_cell = 16'h%04X; // '%s'"
                         % (wi, ci, enc_cell(ch), ch))
    lines.append("            default: O_cell = 16'hFFFF;")
    lines.append("        endcase")
    lines.append("    end")
    lines.append("endmodule")
    with open(OUT_TXT, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

def emit_bram_hex(char_index, glyphs):
    """A2: BRAM 初始化 hex（$readmemh 用）：地址 = index*16+row，数据 = 16bit 行位图。
    与 font_rom_cjk.v 的 mem[{I_index, I_row}] 寻址严格对应。深度 4096。"""
    depth = 4096
    out = os.path.join(HERE, "..", "rtl", "video", "font_cjk_bram.hex")
    rows = ["0000"] * 16          # index 0 = blank
    for ch, idx in sorted(char_index.items(), key=lambda kv: kv[1]):
        for bits in glyphs[ch]:
            rows.append("%04X" % bits)
    rows += ["0000"] * (depth - len(rows))
    nl = chr(10)
    with open(out, "w", newline="") as f:
        f.write(nl.join(rows) + nl)

def emit_hex(char_index, glyphs):
    with open(OUT_HEX, "w", newline="\n") as f:
        for ch, idx in sorted(char_index.items(), key=lambda kv: kv[1]):
            val = 0
            for r, bits in enumerate(glyphs[ch]):
                val |= bits << (240 - 16 * r)
            f.write("%064X\n" % val)

if __name__ == "__main__":
    lines = load_strings()
    chars = build_charset(lines + [t for _, t in WINDOWS])
    glyphs = rasterize(chars)
    char_index = {ch: i + 1 for i, ch in enumerate(chars)}
    emit_rom(char_index, glyphs)
    emit_text_rom(char_index)
    emit_hex(char_index, glyphs)
    emit_bram_hex(char_index, glyphs)
    print("OK: %d CJK glyphs, %d windows -> font_rom_cjk.v / osd_text_rom.v" %
          (len(chars), len(WINDOWS)))
